export const CITY_GROUPS = Object.freeze({
  sport: 10,
  commercial: 8,
  entertainment: 9,
  community: 8,
  special: 2,
});
const bases = {
  sport: 4_000_000,
  commercial: 9_000_000,
  entertainment: 5_000_000,
  community: 4_000_000,
  special: 14_000_000,
};
export const CITY_FACILITIES = Object.freeze(
  rows.map(([id, group, ar, en, fr, effect, value], index) =>
    Object.freeze({
      id,
      group,
      name: { ar, en, fr },
      cost: bases[group] * (1 + (index % 4)),
      upkeep: Math.round(bases[group] * (1 + (index % 4)) * 0.008),
      income: [
        "income",
        "events",
        "fan",
        "matchIncome",
        "seasonTickets",
      ].includes(effect)
        ? Math.round(bases[group] * (1 + (index % 4)) * 0.014)
        : id === "pool" ||
            id === "publicGym" ||
            id === "hotel" ||
            id === "hospital"
          ? 125_000
          : 0,
      effect,
      value,
    }),
  ),
);
export const cityFacility = (id) => CITY_FACILITIES.find((x) => x.id === id);
