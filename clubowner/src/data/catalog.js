export function makePlayers(clubId, leagues) {
  const own = names.map((name, i) =>
    makePlayer("p" + i, name, clubId, "eg", i, true),
  );
  const marketNames = {
    eg: [
      "ياسين شريف",
      "معتز داود",
      "نور إبراهيم",
      "أدهم صلاح",
      "طارق رضوان",
      "محمود عبد الهادي",
    ],
    en: [
      "أوليفر ريد",
      "ليام كوبر",
      "نوح ووكر",
      "إيثان بليك",
      "جاك موريس",
      "لوك بنتلي",
    ],
    sa: [
      "سعود ناصر",
      "فهد الدوسري",
      "عبد الله حاتم",
      "راكان السالم",
      "ماجد الحربي",
      "خالد منصور",
    ],
  };
  const market = leagues.flatMap((l, j) =>
    marketNames[l].map((n, i) =>
      makePlayer(
        `m-${l}-${i}`,
        n,
        l === "eg"
          ? "نادي مصري تجريبي"
          : l === "en"
            ? "نادي إنجليزي تجريبي"
            : "نادي سعودي تجريبي",
        l,
        i + j * 6,
        false,
      ),
    ),
  );
  return [...own, ...market];
}
export function makePlayer(id, name, clubId, league, i, own) {
  const positions = [
    "GK",
    "CB",
    "CB",
    "RB",
    "LB",
    "DM",
    "CM",
    "CM",
    "RW",
    "LW",
    "ST",
    "GK",
    "CB",
    "DM",
    "AM",
    "ST",
    "RW",
    "LB",
  ];
  const rating = own ? 64 + ((i * 7) % 17) : 67 + ((i * 5) % 16);
  return {
    fictional: true,
    id,
    name,
    clubId,
    league,
    position: positions[i % positions.length],
    age: 19 + ((i * 3) % 14),
    rating,
    potential: Math.min(94, rating + 5 + (i % 9)),
    foot: i % 4 === 0 ? "يسرى" : "يمنى",
    nationality:
      league === "en" ? "إنجليزي" : league === "sa" ? "سعودي" : "مصري",
    value: (rating - 56) * 500000,
    salary: (rating - 50) * 6500,
    morale: 75 + (i % 12),
    fitness: 90 + (i % 10),
    contractEnd: "2028-06-30",
    role: i < 11 ? "أساسي" : "مداورة",
    attributes: {
      pace: Math.min(94, rating + 4 - (i % 7)),
      passing: rating - 2 + (i % 5),
      shooting: positions[i % 18] === "GK" ? 25 : rating - 7 + (i % 11),
      defending: rating - 4 + (i % 8),
      stamina: rating + 2,
      decisions: rating - 3,
    },
    appearances: 0,
    goals: 0,
    fictional: true,
  };
}
